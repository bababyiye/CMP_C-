// main.cpp
// Purpose: entry point of the registry lab utility. Runs, in order,
//          every WinAPI registry task required by the lab: listing
//          autostart entries, adding a new one, re-listing to confirm
//          it, listing scheduled tasks from the registry, and
//          exporting a registry key into a .reg file.
// Author:  Zinchenko Maksym, group IPZ-23-5
#include <windows.h>
#include <iostream>
#include <string>
#include <cstring>

#include "AutoStart.h"
#include "TaskScheduler.h"
#include "RegExporter.h"
#include "utils.h"

namespace
{
    // Creates a small demonstration key with a couple of values, so
    // that task 8 (export to .reg) has predictable, harmless data to
    // work with, and so that RegCreateKeyEx / RegSetValueEx /
    // RegDeleteValue / RegDeleteKey (listed among the required API in
    // the lab) are all exercised at least once.
    void PrepareDemoKey()
    {
        PrintSectionTitle("PREPARE DEMO KEY FOR EXPORT (RegCreateKeyEx)");

        HKEY hKey;
        DWORD disposition = 0;
        LONG result = RegCreateKeyExA(
            HKEY_CURRENT_USER,
            "Software\\MyCopy",
            0, nullptr, 0,
            KEY_WRITE, nullptr,
            &hKey, &disposition);

        if (result != ERROR_SUCCESS)
        {
            std::cout << "Failed to create HKCU\\Software\\MyCopy. Error code: "
                      << result << "\n";
            return;
        }

        const char* textValue = "value";
        RegSetValueExA(hKey, "Param1", 0, REG_SZ,
            reinterpret_cast<const BYTE*>(textValue),
            static_cast<DWORD>(strlen(textValue) + 1));

        DWORD numberValue = 5;
        RegSetValueExA(hKey, "Number", 0, REG_DWORD,
            reinterpret_cast<const BYTE*>(&numberValue), sizeof(numberValue));

        RegCloseKey(hKey);

        std::cout << "HKEY_CURRENT_USER\\Software\\MyCopy created with values "
                  << "\"Param1\"=\"value\" and \"Number\"=5.\n";
    }

    // Removes the demonstration key created above, to demonstrate
    // RegDeleteValue and RegDeleteKey and to leave the registry clean
    // after the lab has been checked.
    void CleanupDemoKey()
    {
        PrintSectionTitle("CLEANUP DEMO KEY (RegDeleteValue / RegDeleteKey)");

        HKEY hKey;
        LONG openResult = RegOpenKeyExA(
            HKEY_CURRENT_USER, "Software\\MyCopy", 0, KEY_SET_VALUE, &hKey);

        if (openResult == ERROR_SUCCESS)
        {
            RegDeleteValueA(hKey, "Param1");
            RegCloseKey(hKey);
        }

        LONG deleteResult = RegDeleteKeyA(HKEY_CURRENT_USER, "Software\\MyCopy");
        if (deleteResult == ERROR_SUCCESS)
            std::cout << "HKEY_CURRENT_USER\\Software\\MyCopy removed.\n";
        else
            std::cout << "Failed to remove the demo key. Error code: " << deleteResult << "\n";
    }
}

int main()
{
    std::cout << "=====================================================\n";
    std::cout << "        Windows Registry lab utility (lab 4)         \n";
    std::cout << "=====================================================\n";

    // ---- Task 4: list current autostart entries ----
    std::cout << "\n--- BEFORE adding a new entry ---\n";
    ListAutoStartEntries();

    // ---- Task 5: add a new autostart entry ----
    AddAutoStartEntry("MyAutoStartApp",
        "C:\\Program Files\\Microsoft Office\\root\\Office16\\WINWORD.EXE");

    // ---- Task 6: re-list and confirm the entry is present ----
    std::cout << "\n--- AFTER adding the new entry ---\n";
    ListAutoStartEntries();

    // ---- Task 7: list scheduled tasks directly from the registry ----
    ListScheduledTasksFromRegistry();

    // ---- Task 8: export a registry key into a .reg file ----
    PrepareDemoKey();
    ExportKeyToRegFile(HKEY_CURRENT_USER, "HKEY_CURRENT_USER", "Software\\MyCopy",
        "registry_export.reg");
    CleanupDemoKey();

    std::cout << "\nAll tasks completed.\n";
    std::cout << "See registry_export.reg for the exported key (task 8).\n";
    std::cout << "ttt_association.reg (task 9) was prepared separately and is not\n";
    std::cout << "generated by this program - import it manually to test the\n";
    std::cout << ".ttt -> Notepad file association.\n";

    return 0;
}

