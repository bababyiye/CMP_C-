// -----------------------------------------------------------------------
// Файл:       program4_quicksort_desc.cpp
// Призначення: Програма №4 (додаткове завдання). Працює ПАРАЛЕЛЬНО з
//              програмами №1, №2, №3 і сортує ТОЙ САМИЙ масив у MMF,
//              але:
//                - іншим алгоритмом (QuickSort замість Bubble Sort);
//                - у ЗВОРОТНОМУ напрямку (за спаданням).
//              Оскільки два процеси (програма №1 і програма №4)
//              одночасно намагаються сортувати один масив у протилежних
//              напрямках, критична секція повинна повністю блокувати
//              доступ до масиву на час КОЖНОГО кроку перестановки, щоб
//              не виникало "перегонів даних" (data race).
// Автор:      Зінченко Максим Вячеславович, гр. ІПЗ-23-5
// -----------------------------------------------------------------------
#include "common.h"
#include <conio.h>

// -----------------------------------------------------------------------
// ФУНКЦІЯ:  PartitionStepDesc
// ПОВЕРТАЄ: int - позиція опорного елемента (pivot) після розбиття
// ПАРАМЕТРИ:
//   ctx  - контекст MMF з масивом
//   low  - нижня межа поточного підмасиву
//   high - верхня межа поточного підмасиву (індекс опорного елемента)
// ВИКОНУЄ:  Стандартне розбиття Лом'юто (Lomuto partition scheme), але
//           з ІНВЕРТОВАНОЮ умовою порівняння (>= замість <=), завдяки
//           чому результат виходить відсортованим за СПАДАННЯМ.
// ОСОБЛИВОСТІ:
//   Кожна перестановка (swap) відбувається під тим самим мьютексом,
//   що використовує програма №1 - це критично, інакше два
//   сортувальники "битимуться" за одні й ті самі елементи масиву й
//   зруйнують коректність обох алгоритмів.
// -----------------------------------------------------------------------
int PartitionStepDesc(MmfContext& ctx, int low, int high)
{
    int pivot = ctx.pData[high];
    int i = low - 1;

    for (int j = low; j < high; ++j)
    {
        // ">=" замість "<=" - обертає напрямок сортування на спадання
        if (ctx.pData[j] >= pivot)
        {
            ++i;
            int tmp = ctx.pData[i];
            ctx.pData[i] = ctx.pData[j];
            ctx.pData[j] = tmp;
        }
    }
    int tmp = ctx.pData[i + 1];
    ctx.pData[i + 1] = ctx.pData[high];
    ctx.pData[high] = tmp;
    return i + 1;
}

// -----------------------------------------------------------------------
// ФУНКЦІЯ:  QuickSortDescRecursive
// ПОВЕРТАЄ: нічого (void)
// ПАРАМЕТРИ:
//   ctx        - контекст MMF з масивом
//   low, high  - межі поточного підмасиву
// ВИКОНУЄ:  Рекурсивний QuickSort за спаданням. КОЖЕН виклик
//           PartitionStepDesc обгорнутий у окрему критичну секцію
//           (Lock/Unlock), а не весь QuickSort цілком - інакше
//           програма №4 монопольно тримала б мьютекс до завершення
//           всього сортування, роблячи паралельну роботу програми №1
//           та оновлення програми №2 неможливими.
// ОСОБЛИВОСТІ:
//   Після кожного кроку розбиття виконується FlushViewOfFile та
//   невелика затримка (300 мс) - це навмисно повільніше за QuickSort
//   "на повній швидкості", щоб два сортувальники встигали видимо
//   "боротися" за масив, а не завершити роботу миттєво.
// -----------------------------------------------------------------------
void QuickSortDescRecursive(MmfContext& ctx, int low, int high)
{
    if (low >= high) return;

    int pivotIndex = -1;

    // ---------------- Критична секція: один крок розбиття ----------------
    if (LockMmf(ctx.hMutex, 5000))
    {
        pivotIndex = PartitionStepDesc(ctx, low, high);
        FlushViewOfFile(ctx.pData, 0);
        UnlockMmf(ctx.hMutex);
    }
    else
    {
        wprintf(L"[Програма №4] Таймаут мьютекса на діапазоні [%d;%d] "
                L"- повторна спроба\n", low, high);
        Sleep(200);
        QuickSortDescRecursive(ctx, low, high); // повторити той самий крок
        return;
    }
    // ------------------- Кінець критичної секції --------------------------

    Sleep(300); // штучна затримка поза локом - даємо шанс програмі №1

    QuickSortDescRecursive(ctx, low, pivotIndex - 1);
    QuickSortDescRecursive(ctx, pivotIndex + 1, high);
}

int wmain()
{
    wprintf(L"=== Програма №4: Паралельний QuickSort (спадання) ===\n");
    wprintf(L"Натисніть ПРОБІЛ, щоб почати сортування за спаданням, "
            L"або ESC для виходу...\n");
    wprintf(L"УВАГА: запускайте паралельно з програмою №1 для "
            L"демонстрації конкуренції за спільний масив.\n");

    bool running = true;
    while (running)
    {
        if (_kbhit())
        {
            int ch = _getch();

            if (ch == ' ')
            {
                MmfContext ctx;

                ctx.hMutex = OpenNamedMutexOrCreate();
                if (ctx.hMutex == nullptr)
                {
                    wprintf(L"Не вдалося створити/відкрити мьютекс.\n");
                    continue;
                }

                if (!OpenExistingDataMmf(ctx))
                {
                    wprintf(L"Не вдалося підготувати MMF. Переконайтесь, "
                            L"що програма №3 була запущена першою.\n");
                    ReleaseMmfContext(ctx);
                    continue;
                }

                wprintf(L"Починаю QuickSort за спаданням, %lu "
                        L"елементів...\n", ctx.dwCount);

                QuickSortDescRecursive(
                    ctx, 0, static_cast<int>(ctx.dwCount) - 1);

                wprintf(L"Робота завершена\n");

                ReleaseMmfContext(ctx);

                wprintf(L"\nНатисніть ПРОБІЛ, щоб повторити, "
                        L"або ESC для виходу...\n");
            }
            else if (ch == 27)
            {
                running = false;
            }
        }
        else
        {
            Sleep(50);
        }
    }

    wprintf(L"Завершення програми №4.\n");
    return 0;
}
