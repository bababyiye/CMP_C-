// -----------------------------------------------------------------------
// Файл:       program1_sort_console.cpp
// Призначення: Програма №1 "Сортування даних" (консольна, на основі
//              "Hello Windows"). Очікує натискання клавіші "пробіл",
//              після чого відображає data.dat у пам'ять через MMF і
//              виконує сортування масиву з затримкою 1 секунда після
//              кожної ітерації. Усі зміни відразу видно програмі №2,
//              оскільки обидві програми мапують ОДИН і той самий файл.
// Автор:      Зінченко Максим Вячеславович, гр. ІПЗ-23-5
// -----------------------------------------------------------------------
#include "common.h"
#include <conio.h>   // _kbhit(), _getch() - опитування клавіатури в консолі

// -----------------------------------------------------------------------
// ФУНКЦІЯ:  BubbleSortStep
// ПОВЕРТАЄ: bool - true, якщо на цьому проході відбулась хоча б одна
//           перестановка (масив ще не відсортований)
// ПАРАМЕТРИ:
//   ctx - контекст MMF з вказівником на масив та кількістю елементів
// ВИКОНУЄ:  Один прохід ("одна ітерація") бульбашкового сортування:
//           порівнює сусідні елементи масиву у MMF і, якщо потрібно,
//           міняє їх місцями. Весь прохід виконується під захистом
//           мьютекса (викликається зовні з уже захопленим лочком),
//           щоб програма №4 (сортувальник у зворотному напрямку) не
//           могла одночасно змінювати ті самі елементи.
// ОСОБЛИВОСТІ:
//   Обрано бульбашкове сортування (Bubble Sort) свідомо: воно виконує
//   рівно один "прохід" за виклик, що дозволяє природно вставити
//   затримку в 1 секунду між ітераціями та наочно спостерігати процес
//   у програмі №2 (візуалізації).
// -----------------------------------------------------------------------
bool BubbleSortStep(MmfContext& ctx)
{
    bool swapped = false;
    for (DWORD i = 0; i + 1 < ctx.dwCount; ++i)
    {
        if (ctx.pData[i] > ctx.pData[i + 1])
        {
            int tmp = ctx.pData[i];
            ctx.pData[i] = ctx.pData[i + 1];
            ctx.pData[i + 1] = tmp;
            swapped = true;
        }
    }
    return swapped;
}

// -----------------------------------------------------------------------
// ФУНКЦІЯ:  RunSortingLoop
// ПОВЕРТАЄ: нічого (void)
// ПАРАМЕТРИ:
//   ctx - контекст MMF, дані якого потрібно відсортувати
// ВИКОНУЄ:  Цикл ітерацій бульбашкового сортування. Кожна ітерація:
//           1. Захоплює мьютекс (критична секція);
//           2. Виконує один прохід BubbleSortStep;
//           3. Скидає зміни у файл (FlushViewOfFile) - за вимогою
//              "зберігати зміни безпосередньо у MMF";
//           4. Звільняє мьютекс;
//           5. Чекає 1 секунду (Sleep) - ПОЗА критичною секцією, щоб
//              не блокувати інші процеси (програму №2 на весь час
//              затримки).
//           Цикл триває, доки прохід не пройде без жодної перестановки.
// ОСОБЛИВОСТІ:
//   Затримка винесена за межі критичної секції навмисно: утримання
//   мьютекса протягом секунди без потреби - приклад "надто широкої"
//   критичної секції, яка без причини блокує інші процеси
//   (напр. програму №4) і збільшує ризик виявленого таймауту/deadlock.
// -----------------------------------------------------------------------
void RunSortingLoop(MmfContext& ctx)
{
    wprintf(L"Починаю сортування (Bubble Sort), %lu елементів...\n",
            ctx.dwCount);

    bool swapped = true;
    int iteration = 0;

    while (swapped)
    {
        ++iteration;

        // ---------------- Критична секція ----------------
        if (!LockMmf(ctx.hMutex, 5000)) // таймаут 5с - виявлення deadlock
        {
            wprintf(L"Не вдалося захопити мьютекс на ітерації %d - "
                    L"пропускаю прохід\n", iteration);
            Sleep(1000);
            continue;
        }

        swapped = BubbleSortStep(ctx);

        if (!FlushViewOfFile(ctx.pData, 0))
        {
            PrintLastError("FlushViewOfFile");
        }

        UnlockMmf(ctx.hMutex);
        // -------------- Кінець критичної секції --------------

        wprintf(L"Ітерація %d: ", iteration);
        for (DWORD i = 0; i < ctx.dwCount; ++i)
            wprintf(L"%d ", ctx.pData[i]);
        wprintf(L"\n");

        Sleep(1000); // затримка 1 секунда, поза критичною секцією
    }

    wprintf(L"Робота завершена\n");
}

int wmain()
{
    wprintf(L"=== Програма №1: Сортування даних ===\n");
    wprintf(L"(на основі \"Hello Windows\")\n");
    wprintf(L"Натисніть ПРОБІЛ, щоб почати сортування, або "
            L"ESC для виходу...\n");

    // ------------------------------------------------------------
    // Цикл обробки натискань клавіш у консольному режимі.
    // _kbhit() перевіряє, чи є подія клавіатури в буфері, не
    // блокуючи виконання - завдяки цьому програма залишається
    // "живою" (наприклад, могла б паралельно оновлювати статус).
    // ------------------------------------------------------------
    bool running = true;
    while (running)
    {
        if (_kbhit())
        {
            int ch = _getch();

            if (ch == ' ')
            {
                MmfContext ctx;

                // Крок 1: підключення до мьютекса синхронізації
                ctx.hMutex = OpenNamedMutexOrCreate();
                if (ctx.hMutex == nullptr)
                {
                    wprintf(L"Не вдалося створити/відкрити мьютекс. "
                            L"Роботу перервано.\n");
                    continue;
                }

                // Крок 2: відкриття файлу data.dat та MMF
                if (!OpenExistingDataMmf(ctx))
                {
                    wprintf(L"Не вдалося підготувати MMF. "
                            L"Переконайтесь, що програма №3 була "
                            L"запущена першою.\n");
                    ReleaseMmfContext(ctx);
                    continue;
                }

                // Крок 3: власне сортування
                RunSortingLoop(ctx);

                // Крок 4: звільнення усіх ресурсів
                ReleaseMmfContext(ctx);

                wprintf(L"\nНатисніть ПРОБІЛ, щоб відсортувати ще раз, "
                        L"або ESC для виходу...\n");
            }
            else if (ch == 27) // ESC
            {
                running = false;
            }
        }
        else
        {
            Sleep(50); // не навантажувати CPU опитуванням клавіатури
        }
    }

    wprintf(L"Завершення програми №1.\n");
    return 0;
}
